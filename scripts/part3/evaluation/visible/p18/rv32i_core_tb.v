    function [31:0] sext; input [31:0] v; input integer bits;
        begin sext = (v << (32 - bits)); sext = $signed(sext) >>> (32 - bits); end
    endfunction

    task predict;                       // decode + execute the instruction at pc (no state change)
        reg [31:0] in, a, b, imm, ea, w, sh;
        reg [6:0] op; reg [2:0] f3; reg [4:0] rd, rs1, rs2;
        reg taken;
        integer k;
        begin
            in = imem[pc[11:2]];
            op = in[6:0]; rd = in[11:7]; f3 = in[14:12]; rs1 = in[19:15]; rs2 = in[24:20];
            a = x[rs1]; b = x[rs2];
            e_re = 0; e_addr = 0; e_wstrb = 0; e_wdata = 0; e_mwdata = 0; e_ea = 0;
            e_rd = 0; e_rdw = 0; e_npc = pc + 4;
            case (op)
                7'b0110111: begin e_rd = rd; e_rdw = {in[31:12], 12'd0}; end
                7'b0010111: begin e_rd = rd; e_rdw = pc + {in[31:12], 12'd0}; end
                7'b1101111: begin e_rd = rd; e_rdw = pc + 4;
                                  e_npc = pc + sext({in[31], in[19:12], in[20], in[30:21], 1'b0}, 21); end
                7'b1100111: begin e_rd = rd; e_rdw = pc + 4;
                                  e_npc = (a + sext(in[31:20], 12)) & ~32'd1; end
                7'b1100011: begin
                    case (f3)
                        0: taken = a == b;  1: taken = a != b;
                        4: taken = $signed(a) <  $signed(b);  5: taken = $signed(a) >= $signed(b);
                        6: taken = a < b;   7: taken = a >= b;
                        default: taken = 0;
                    endcase
                    if (taken) e_npc = pc + sext({in[31], in[7], in[30:25], in[11:8], 1'b0}, 13);
                end
                7'b0000011: begin
                    ea = a + sext(in[31:20], 12);
                    e_ea = ea; e_re = 1; e_addr = {ea[31:2], 2'b00}; e_rd = rd;
                    w = mm[ea[11:2]] >> (8 * ea[1:0]);
                    case (f3)
                        0: e_rdw = sext(w[7:0], 8);
                        1: e_rdw = sext(w[15:0], 16);
                        4: e_rdw = w[7:0];
                        5: e_rdw = w[15:0];
                        default: e_rdw = mm[ea[11:2]];
                    endcase
                end
                7'b0100011: begin
                    ea = a + sext({in[31:25], in[11:7]}, 12);
                    e_ea = ea; e_addr = {ea[31:2], 2'b00};
                    case (f3[1:0])
                        0: begin e_wstrb = 4'b0001 << ea[1:0]; e_wdata = {4{b[7:0]}}; end
                        1: begin e_wstrb = ea[1] ? 4'b1100 : 4'b0011; e_wdata = {2{b[15:0]}}; end
                        default: begin e_wstrb = 4'b1111; e_wdata = b; end
                    endcase
                    for (k = 0; k < 4; k = k + 1)
                        if (e_wstrb[k]) e_mwdata = e_mwdata | (e_wdata & (32'hFF << (8 * k)));
                end
                7'b0010011, 7'b0110011: begin
                    imm = (op == 7'b0110011) ? b : sext(in[31:20], 12);
                    sh = imm[4:0];
                    e_rd = rd;
                    case (f3)
                        0: e_rdw = (op == 7'b0110011 && in[30]) ? a - imm : a + imm;
                        1: e_rdw = a << sh;
                        2: e_rdw = ($signed(a) < $signed(imm)) ? 1 : 0;
                        3: e_rdw = (a < imm) ? 1 : 0;
                        4: e_rdw = a ^ imm;
                        5: if (in[30]) e_rdw = $signed(a) >>> sh; else e_rdw = a >> sh;
                        6: e_rdw = a | imm;
                        7: e_rdw = a & imm;
                    endcase
                end
                default: ;                       // unknown opcode: no-op
            endcase
            if (e_rd == 0) e_rdw = 0;
        end
    endtask

    task commit;                        // the state change of the predicted instruction
        integer k;
        begin
            if (e_rd != 0) x[e_rd] = e_rdw;
            for (k = 0; k < 4; k = k + 1)
                if (e_wstrb[k]) mm[e_addr[11:2]] = (mm[e_addr[11:2]] & ~(32'hFF << (8 * k))) | (e_wdata & (32'hFF << (8 * k)));
            pc = e_npc;
        end
    endtask

    task fail; input [8*40-1:0] what; input [31:0] got, exp;
        begin
            errors = errors + 1;
            if (errors <= 25) $display("ERROR: cycle %0d pc=%h insn=%h: %0s = %h, expected %h", cyc, pc, imem[pc[11:2]], what, got, exp);
        end
    endtask

    task load_and_reset; input integer p;
        integer k;
        begin
            reset = 1;
            for (k = 0; k < 1024; k = k + 1) begin
                imem[k] = 32'h00000013;
                dmem[k] = k * 32'h9E3779B1 + 32'h12345678;
                mm[k]   = dmem[k];
            end
            for (k = 0; k < len[p]; k = k + 1) imem[k] = progs[start[p] + k];
            for (k = 0; k < 32; k = k + 1) x[k] = 0;
            pc = 0;
            @(negedge clk); @(negedge clk);
            checks = checks + 1;
            if (retire_valid !== 1'b0 || imem_addr !== 32'd0 || dmem_wstrb !== 4'd0) begin
                errors = errors + 1; $display("ERROR: after reset: retire_valid=%b imem_addr=%h dmem_wstrb=%b", retire_valid, imem_addr, dmem_wstrb);
            end
            reset = 0;
        end
    endtask

    task run; input integer n;          // n instructions, checked before and after every edge
        integer k;
        begin
            for (k = 0; k < n; k = k + 1) begin
                cyc = cyc + 1;
                predict;
                #1;
                checks = checks + 1;
                if (dmem_re !== e_re) fail("dmem_re", dmem_re, e_re);
                if (e_re && dmem_addr !== e_addr) fail("dmem_addr (load)", dmem_addr, e_addr);
                if (dmem_wstrb !== e_wstrb) fail("dmem_wstrb", dmem_wstrb, e_wstrb);
                if (e_wstrb != 0 && dmem_addr !== e_addr) fail("dmem_addr (store)", dmem_addr, e_addr);
                if (e_wstrb != 0 && ((dmem_wdata ^ e_wdata) & e_mwdata_mask(e_wstrb)) !== 0) fail("dmem_wdata", dmem_wdata, e_wdata);
                @(negedge clk);                 // one rising edge
                if (retire_valid !== 1'b1)           fail("retire_valid", retire_valid, 1);
                if (retire_pc !== pc)                fail("retire_pc", retire_pc, pc);
                if (retire_insn !== imem[pc[11:2]])  fail("retire_insn", retire_insn, imem[pc[11:2]]);
                if (retire_rd !== e_rd)              fail("retire_rd", retire_rd, e_rd);
                if (retire_rd_wdata !== e_rdw)       fail("retire_rd_wdata", retire_rd_wdata, e_rdw);
                if (retire_mem_addr !== e_ea)        fail("retire_mem_addr", retire_mem_addr, e_ea);
                if (retire_mem_wstrb !== e_wstrb)    fail("retire_mem_wstrb", retire_mem_wstrb, e_wstrb);
                if (retire_mem_wdata !== e_mwdata)   fail("retire_mem_wdata", retire_mem_wdata, e_mwdata);
                commit;
                if (imem_addr !== pc)                fail("imem_addr (next pc)", imem_addr, pc);
            end
        end
    endtask

    function [31:0] e_mwdata_mask; input [3:0] s;
        e_mwdata_mask = {{8{s[3]}}, {8{s[2]}}, {8{s[1]}}, {8{s[0]}}};
    endfunction

    initial clk = 0;
    always #5 clk = ~clk;

    integer p, q;
    initial begin
        errors = 0; checks = 0; cyc = 0; reset = 1;
        for (p = 0; p <= 9; p = p + 1) begin
            load_and_reset(p);
            run(len[p] + 40);
            if (p == 4) begin                       // reset in the middle of a program, then run it again
                load_and_reset(p);
                run(60);
                load_and_reset(p);
                run(len[p] + 40);
            end
        end
        // the data memory must hold what the model stored
        for (q = 0; q < 1024; q = q + 1)
            if (dmem[q] !== mm[q]) begin errors = errors + 1;
                if (errors <= 25) $display("ERROR: data memory word %0d = %h, expected %h", q, dmem[q], mm[q]); end
        if (errors == 0) $display("Test PASSED! (%0d programs, %0d checks)", 9 + 1, checks);
        else             $display("Test FAILED: %0d errors found.", errors);
        $finish;
    end
